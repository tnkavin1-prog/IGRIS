<#
.SYNOPSIS
  First-run setup for Gemini Browser Live on Windows.

.DESCRIPTION
  Derives the stable extension id from the manifest key, generates a strong
  local gate secret, and writes apps/local-bridge/.env. The Gemini API key is
  stored only in that file, which is gitignored; it never enters Chrome.

.PARAMETER ApiKey
  Gemini API key. If omitted, the script reads GEMINI_API_KEY or prompts without
  echoing the value.

.PARAMETER Port
  Loopback port for the bridge. Defaults to 47821.

.PARAMETER Force
  Overwrite an existing .env file.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts/setup-windows.ps1
#>
[CmdletBinding()]
param(
  [string]$ApiKey,
  [int]$Port = 47821,
  [switch]$Force
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$manifestPath = Join-Path $root 'apps\chrome-extension\manifest.json'
$envPath = Join-Path $root 'apps\local-bridge\.env'

if (-not (Test-Path $manifestPath)) {
  throw "Manifest not found: $manifestPath"
}
if ((Test-Path $envPath) -and -not $Force) {
  Write-Host ''
  Write-Host "  apps/local-bridge/.env already exists." -ForegroundColor Yellow
  Write-Host '  Re-run with -Force to replace it (the existing gate secret will stop working).'
  Write-Host ''
  exit 1
}

# -- Stable extension id: SHA-256 of the DER key, first 16 bytes, nibbles -> a-p.
$manifest = Get-Content $manifestPath -Raw | ConvertFrom-Json
if (-not $manifest.key) {
  throw 'manifest.json has no "key"; a stable extension id cannot be derived.'
}
$sha = [System.Security.Cryptography.SHA256]::Create()
try {
  $digest = $sha.ComputeHash([Convert]::FromBase64String($manifest.key))
} finally {
  $sha.Dispose()
}
$alphabet = 'abcdefghijklmnop'
$extensionId = -join (0..15 | ForEach-Object {
  $byte = $digest[$_]
  $alphabet[$byte -shr 4] + $alphabet[$byte -band 0x0F]
})

# -- API key: argument -> environment -> hidden prompt.
if (-not $ApiKey) {
  $ApiKey = $env:GEMINI_API_KEY
}
if (-not $ApiKey) {
  $secure = Read-Host -AsSecureString 'Paste the Gemini API key (input is hidden)'
  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
  try {
    $ApiKey = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
  } finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
  }
}
$ApiKey = $ApiKey.Trim()
if ($ApiKey.Length -lt 20 -or $ApiKey -match '\s') {
  throw 'The API key looks invalid (too short or contains whitespace).'
}

# -- Gate secret: 32 random bytes, base64url encoded (43 chars).
$secretBytes = New-Object byte[] 32
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try {
  $rng.GetBytes($secretBytes)
} finally {
  $rng.Dispose()
}
$gateSecret = [Convert]::ToBase64String($secretBytes).Replace('+', '-').Replace('/', '_').TrimEnd('=')

$lines = @(
  '# Generated by scripts/setup-windows.ps1 - never commit this file.',
  "GEMINI_API_KEY=$ApiKey",
  "LOCAL_GATE_SECRET=$gateSecret",
  "PORT=$Port",
  "ALLOWED_EXTENSION_IDS=$extensionId",
  'TOKEN_TTL_MINUTES=30',
  'NEW_SESSION_TTL_SECONDS=60',
  'RATE_LIMIT_PER_MINUTE=30',
  'LOG_LEVEL=info',
  'ALLOWED_ORIGINS='
)
# Write UTF-8 without a BOM so the first key is parsed as GEMINI_API_KEY rather
# than a BOM-prefixed key. PowerShell 5.1's -Encoding UTF8 emits a BOM.
[System.IO.File]::WriteAllText(
  $envPath,
  ($lines -join "`r`n") + "`r`n",
  (New-Object System.Text.UTF8Encoding($false))
)
# Best-effort tightening; ignored on filesystems without ACL support.
try {
  $acl = Get-Acl $envPath
  $acl.SetAccessRuleProtection($true, $false)
  $rule = New-Object System.Security.AccessControl.FileSystemAccessRule(
    [System.Security.Principal.WindowsIdentity]::GetCurrent().Name,
    'FullControl',
    'Allow'
  )
  $acl.SetAccessRule($rule)
  Set-Acl -Path $envPath -AclObject $acl
} catch {
  Write-Verbose "Could not restrict .env ACL: $_"
}

Write-Host ''
Write-Host '  Gemini Browser Live - setup complete' -ForegroundColor Green
Write-Host ''
Write-Host "  Extension id : $extensionId"
Write-Host "  Bridge port  : $Port"
Write-Host "  Config file  : $envPath"
Write-Host ''
Write-Host '  Paste this gate secret into the side panel -> Settings -> Connection:' -ForegroundColor Cyan
Write-Host "  $gateSecret" -ForegroundColor White
Write-Host ''
Write-Host '  Next steps:'
Write-Host '    1. npm run build'
Write-Host '    2. npm run bridge        (keep this window open)'
Write-Host '    3. chrome://extensions -> Developer mode -> Load unpacked -> release/chrome-extension'
Write-Host '    4. Open the side panel and pair with the gate secret above.'
Write-Host ''
Write-Host '  The Gemini API key stays in the bridge process; do not share .env.' -ForegroundColor Yellow
Write-Host ''
